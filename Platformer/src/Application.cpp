constexpr unsigned int indices[] = {
    0, 1, 2, 3, 4, 5,       // face arrière
    6, 7, 8, 9, 10, 11,     // face avant
    12, 13, 14, 15, 16, 17, // face gauche
    18, 19, 20, 21, 22, 23, // face droite
    24, 25, 26, 27, 28, 29, // face bas
    30, 31, 32, 33, 34, 35  // face haut
};
Application::Application(const int width, const int height, std::string title) : window(width, height, title),
                                                                                 ebo(indices, sizeof(indices)),
                                                                                 vbo(vertices, sizeof(vertices)),
                                                                                 shader("assets/shaders/basic.vert", "assets/shaders/basic.frag"),
                                                                                 texture1(Atelier::Graphics::TextureData("assets/texture/container.jpg"))

{
    Atelier::OpenGL::VertexLayout layout;
    layout.addFloat(3);
    layout.addFloat(2);

    vao.addVertexLayout(layout, vbo);
    vao.setIndexBuffer(ebo);
    vao.unbind();

    window.setResizeCallback([this](int w, int h)
                             { renderer.setViewport(w, h); });
}

Application::~Application()
{
}

void Application::run()
{
    while (!window.shouldClose())
    {
        glm::mat4 view = glm::mat4(1.0f);
        glm::mat4 projection = glm::mat4(1.0f);
        projection = glm::perspective(glm::radians(45.0f), (float)window.getWidth() / (float)window.getHeight(), 1.0f, 100.0f);
        view = glm::translate(view, glm::vec3(0.0f, 0.0f, -3.0f));
        glm::mat4 model = glm::mat4(1.0f);
        model = glm::translate(model, glm::vec3(0.0f, 0.0f, 0.0f));

        renderer.clear(0.2f, 0.3f, 0.3f, 1.0f);

        renderer.draw(vao, shader, texture1, model, view, projection);

        window.pollEvents();
        window.swapBuffers();
    }
}